/** Langues fournies par la librairie. */
export const LANGUES = { fr: FR, en: EN } as const;
export type Langue = keyof typeof LANGUES;

const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

/** Fusion profonde : les tableaux et les textes remplacent ; les objets se complètent. */
function merge<T>(base: T, over: unknown): T {
  if (!isRecord(over) || !isRecord(base)) return (over === undefined ? base : over) as T;
  const out: Record<string, unknown> = { ...base };
  for (const [k, v] of Object.entries(over)) if (v !== undefined) out[k] = merge((base as Record<string, unknown>)[k], v);
  return out as T;
}

/**
 * Textes d'une langue, complétés par les réglages du site. Une langue inconnue reprend le français, ou une autre langue fournie
 * en entier par `base` (« de » à partir d'une traduction maison).
 */
export function textes(langue: string = 'fr', overrides?: TextOverrides, base?: Texts): Texts {
  const start = base ?? (LANGUES as Record<string, Texts>)[langue] ?? FR;
  return merge(start, overrides);
}

/** Remplit les variables « {nom} » d'un texte ; une variable absente reste telle quelle. */
export function fill(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Choisit la forme au singulier (n = 1, ou 0 en français) ou au pluriel, puis remplit « {n} ». */
export function plural(texts: Texts, n: number, one: string, other: string): string {
  const singular = texts.locale.startsWith('fr') ? Math.abs(n) < 2 : n === 1;
  return fill(singular ? one : other, { n: formatNumber(texts, n) });
}

/** Nombre mis en forme selon la langue des textes (« 1 234 », « 1,234 ») ; « — » s'il n'est pas fini. */
export function formatNumber(texts: Texts, v: number, digits = 0): string {
  return Number.isFinite(v) ? v.toLocaleString(texts.locale, { maximumFractionDigits: digits, minimumFractionDigits: digits }) : '—';
}
